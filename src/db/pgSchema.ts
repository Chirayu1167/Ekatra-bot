/**
 * PostgreSQL baseline schema: a clean equivalent of SQLite v1..v7 (no table-recreate hacks).
 * Type mapping: INTEGER PK → BIGINT identity · TEXT times → TIMESTAMPTZ · 0/1 flags → BOOLEAN
 * · lesson options JSON → JSONB. CHECKs, FKs and the partial per-(phone, org) active index are
 * preserved. Position uniqueness is DEFERRABLE so renumbers/swaps commit atomically without
 * the old negative-number trick (and ON CONFLICT must never target those constraints).
 */
export const PG_BASELINE_SQL = `
CREATE TABLE organisations (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       TEXT NOT NULL UNIQUE,
  name       TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO organisations (slug, name) VALUES ('default', 'Default');

CREATE TABLE courses (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id      BIGINT NOT NULL REFERENCES organisations(id),
  slug        TEXT NOT NULL UNIQUE,
  title       TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status      TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX courses_by_org ON courses(org_id);

CREATE TABLE lessons (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  position   INTEGER NOT NULL,
  title      TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT lessons_course_position_unique UNIQUE (course_id, position) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX lessons_by_course ON lessons(course_id);

CREATE TABLE lesson_items (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
  position  INTEGER NOT NULL CHECK (position >= 1),
  kind      TEXT NOT NULL CHECK (kind IN ('text', 'image', 'document', 'video', 'audio', 'link', 'quiz')),
  text      TEXT,
  url       TEXT,
  options   JSONB,
  CONSTRAINT lesson_items_lesson_position_unique UNIQUE (lesson_id, position) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX lesson_items_by_lesson ON lesson_items(lesson_id);

CREATE TABLE enrollments (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id                  BIGINT NOT NULL REFERENCES organisations(id),
  user_id                 TEXT NOT NULL,
  course_id               BIGINT NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
  status                  TEXT NOT NULL CHECK (status IN ('pending', 'active', 'paused', 'completed')),
  last_delivered_position INTEGER NOT NULL DEFAULT 0 CHECK (last_delivered_position >= 0),
  started_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at            TIMESTAMPTZ,
  UNIQUE (user_id, course_id)
);
CREATE UNIQUE INDEX one_active_enrollment_per_org_user ON enrollments(user_id, org_id) WHERE status = 'active';
CREATE INDEX enrollments_by_course ON enrollments(course_id);
CREATE INDEX enrollments_by_org_user ON enrollments(org_id, user_id);

CREATE TABLE processed_messages (
  message_sid TEXT PRIMARY KEY,
  claimed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE opt_outs (
  user_id     TEXT PRIMARY KEY,
  phone_hash  TEXT UNIQUE,
  opted_out_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE learners (
  user_id      TEXT PRIMARY KEY,
  name         TEXT NOT NULL DEFAULT '',
  consented_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE certificates (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id BIGINT NOT NULL UNIQUE REFERENCES enrollments(id) ON DELETE RESTRICT,
  code          TEXT NOT NULL UNIQUE,
  learner_name  TEXT NOT NULL,
  course_title  TEXT NOT NULL,
  issued_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX certificates_by_enrollment ON certificates(enrollment_id);

CREATE TABLE quiz_answers (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id BIGINT NOT NULL REFERENCES enrollments(id) ON DELETE CASCADE,
  position      INTEGER NOT NULL CHECK (position >= 1),
  chosen        INTEGER NOT NULL CHECK (chosen >= 0),
  correct       BOOLEAN NOT NULL,
  answered_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (enrollment_id, position)
);

CREATE TABLE admin_users (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  org_id     BIGINT REFERENCES organisations(id) ON DELETE RESTRICT,
  name       TEXT NOT NULL DEFAULT '',
  role       TEXT NOT NULL CHECK (role IN ('platform_admin', 'org_admin', 'instructor')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((role = 'platform_admin' AND org_id IS NULL) OR (role != 'platform_admin' AND org_id IS NOT NULL))
);

CREATE TABLE admin_api_keys (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
  key_hash     TEXT NOT NULL UNIQUE,
  prefix       TEXT NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_used_at TIMESTAMPTZ,
  revoked_at   TIMESTAMPTZ,
  expires_at   TIMESTAMPTZ
);
CREATE INDEX admin_api_keys_by_hash ON admin_api_keys(key_hash);

CREATE TABLE audit_log (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id BIGINT REFERENCES admin_users(id) ON DELETE SET NULL,
  org_id        BIGINT REFERENCES organisations(id) ON DELETE SET NULL,
  action        TEXT NOT NULL,
  target        TEXT NOT NULL DEFAULT '',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_by_org_time ON audit_log(org_id, created_at);
`;
