/**
 * Phase 3 durable-delivery schema (migration v2, append-only).
 * Tables: inbound_events, jobs, outbound_messages, outbound_attempts, dead_letters,
 * course_schedules, enrollment_schedules, worker_heartbeat + org delivery defaults.
 * At-least-once design: idempotent inserts (MessageSid / dedupe_key / idempotency_key)
 * make every enqueue safe to retry. Never edited after shipping: append a new migration.
 */
export const PHASE3_DELIVERY_SQL = `
CREATE TABLE inbound_events (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_sid    TEXT NOT NULL UNIQUE,
  from_user      TEXT NOT NULL,
  to_user        TEXT NOT NULL DEFAULT '',
  body           TEXT NOT NULL DEFAULT '',
  raw            JSONB NOT NULL DEFAULT '{}',
  status         TEXT NOT NULL DEFAULT 'received'
                 CHECK (status IN ('received', 'processing', 'completed', 'failed')),
  attempts       INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  correlation_id TEXT NOT NULL DEFAULT '',
  visible_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_error     TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX inbound_events_by_status_visible ON inbound_events(status, visible_at);

-- Durable work queue. Claimed with SELECT ... FOR UPDATE SKIP LOCKED; a stuck
-- 'processing' row whose visible_at passed is reclaimed (crash recovery).
-- (kind, dedupe_key) is UNIQUE so enqueue is idempotent: same work = one row.
CREATE TABLE jobs (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind            TEXT NOT NULL CHECK (kind IN ('inbound_process', 'outbound_send')),
  dedupe_key      TEXT NOT NULL,
  ref_type        TEXT NOT NULL DEFAULT '',
  ref_id          BIGINT,
  payload         JSONB NOT NULL DEFAULT '{}',
  status          TEXT NOT NULL DEFAULT 'queued'
                  CHECK (status IN ('queued', 'processing', 'completed', 'failed')),
  attempts        INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  max_attempts    INTEGER NOT NULL DEFAULT 6 CHECK (max_attempts >= 1),
  run_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  visible_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  locked_by       TEXT,
  last_error      TEXT,
  last_error_code TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (kind, dedupe_key)
);
CREATE INDEX jobs_claim ON jobs(status, run_at);

-- One row per logical send. status is monotonic except queued->sending->sent and the
-- terminal states; delivery callbacks move sent->delivered->read or ->failed.
-- 'unknown' = uncertain outcome (timeout/crash after request): NEVER auto-resent until
-- reconciled via status callback or Twilio lookup. See docs/delivery-architecture.md.
CREATE TABLE outbound_messages (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idempotency_key TEXT NOT NULL UNIQUE,
  org_id          BIGINT REFERENCES organisations(id),
  user_id         TEXT NOT NULL,
  enrollment_id   BIGINT REFERENCES enrollments(id) ON DELETE SET NULL,
  course_id       BIGINT REFERENCES courses(id) ON DELETE SET NULL,
  lesson_position INTEGER,
  kind            TEXT NOT NULL DEFAULT 'reply'
                  CHECK (kind IN ('reply', 'scheduled_lesson', 'certificate', 'system', 'template')),
  messages        JSONB NOT NULL DEFAULT '[]',
  status          TEXT NOT NULL DEFAULT 'queued'
                  CHECK (status IN ('queued', 'sending', 'sent', 'delivered', 'read', 'failed', 'unknown', 'dead_letter')),
  twilio_sid      TEXT,
  error_code      TEXT,
  error_message   TEXT,
  attempts        INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_retry_at   TIMESTAMPTZ,
  sent_at         TIMESTAMPTZ,
  delivered_at    TIMESTAMPTZ,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX outbound_by_status_retry ON outbound_messages(status, next_retry_at);
CREATE INDEX outbound_by_user ON outbound_messages(user_id);
CREATE INDEX outbound_by_twilio_sid ON outbound_messages(twilio_sid);

-- Every send attempt: Twilio MessageSid, outcome and error code. Never updated, only
-- appended; replay creates a new chain on the same message row.
CREATE TABLE outbound_attempts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id    BIGINT NOT NULL REFERENCES outbound_messages(id) ON DELETE CASCADE,
  attempt_no    INTEGER NOT NULL CHECK (attempt_no >= 1),
  twilio_sid    TEXT,
  status        TEXT NOT NULL CHECK (status IN ('sent', 'failed', 'unknown')),
  error_code    TEXT,
  error_message TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (message_id, attempt_no)
);
CREATE INDEX outbound_attempts_by_message ON outbound_attempts(message_id);

-- Terminal failures awaiting an operator: replay (new attempt chain) or discard.
-- Every replay/discard is audit-logged (audit_log.action outbound.replay/discard).
CREATE TABLE dead_letters (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind            TEXT NOT NULL CHECK (kind IN ('inbound', 'outbound')),
  ref_id          BIGINT NOT NULL,
  reason          TEXT NOT NULL DEFAULT '',
  reason_code     TEXT NOT NULL DEFAULT '',
  payload         JSONB NOT NULL DEFAULT '{}',
  status          TEXT NOT NULL DEFAULT 'open'
                  CHECK (status IN ('open', 'replayed', 'discarded')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at     TIMESTAMPTZ,
  resolution_note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX dead_letters_by_status ON dead_letters(status);

-- Per-course schedule (admin-set, org-scoped). daily_time / slots are wall-clock
-- 'HH:MM' in the row's timezone; evaluation is timezone-aware (see scheduler service).
ALTER TABLE organisations ADD COLUMN default_timezone TEXT NOT NULL DEFAULT 'Asia/Kolkata';
ALTER TABLE organisations ADD COLUMN default_daily_time TEXT;
ALTER TABLE organisations ADD COLUMN grace_hours INTEGER NOT NULL DEFAULT 6;

CREATE TABLE course_schedules (
  course_id  BIGINT PRIMARY KEY REFERENCES courses(id) ON DELETE CASCADE,
  org_id     BIGINT NOT NULL REFERENCES organisations(id),
  kind       TEXT NOT NULL DEFAULT 'daily' CHECK (kind IN ('daily', 'custom')),
  daily_time TEXT,
  slots      JSONB,
  timezone   TEXT NOT NULL DEFAULT 'Asia/Kolkata',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Per-enrollment schedule state. A row is created on enrolment (defaults from the org);
-- last_slot_key makes "same due slot = one job" idempotent across ticks and restarts.
CREATE TABLE enrollment_schedules (
  enrollment_id BIGINT PRIMARY KEY REFERENCES enrollments(id) ON DELETE CASCADE,
  timezone      TEXT NOT NULL DEFAULT 'Asia/Kolkata',
  daily_time    TEXT,
  slots         JSONB,
  enabled       BOOLEAN NOT NULL DEFAULT TRUE,
  last_slot_key TEXT,
  last_sent_at  TIMESTAMPTZ,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Worker liveness: every worker loop heartbeats its row; /health stays on the API.
CREATE TABLE worker_heartbeat (
  worker_id TEXT PRIMARY KEY,
  last_beat TIMESTAMPTZ NOT NULL DEFAULT now(),
  hostname  TEXT NOT NULL DEFAULT ''
);
`;

/**
 * Migration v3 (append-only): per-item sent markers for idempotent multi-message lesson retry.
 */
export const PHASE3_ITEM_SENT_SQL = `
CREATE TABLE outbound_message_items (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id    BIGINT NOT NULL REFERENCES outbound_messages(id) ON DELETE CASCADE,
  item_position INTEGER NOT NULL CHECK (item_position >= 0),
  twilio_sid    TEXT,
  sent_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (message_id, item_position)
);
CREATE INDEX outbound_message_items_by_message ON outbound_message_items(message_id);
`;
